func TestSafeFilenameNFCParity(t *testing.T) {
	// Expected outputs generated by unicodedata.normalize("NFC", ...) in Python.
	cases := []struct{ in, want string }{
		{"\u1100\u1161\u11b6.txt", "\uac0f.txt"},
		{"cafe\u0065\u0301.txt", "cafe\u00e9.txt"},
		{"\u0041\u030a.doc", "\u00c5.doc"},
		{"plain.txt", "plain.txt"},
	}
	for _, c := range cases {
		if got := SafeFilename(c.in); got != c.want {
			t.Errorf("SafeFilename(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

