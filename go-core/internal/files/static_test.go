package files

import (
	"encoding/json"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"testing"
)

func loadStatic(t *testing.T) map[string]any {
	t.Helper()
	_, file, _, _ := runtime.Caller(0)
	p := filepath.Join(filepath.Dir(file), "..", "..", "..", "tests", "fixtures", "go_migration", "milestone_c", "static_vectors.json")
	data, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	var v map[string]any
	if err := json.Unmarshal(data, &v); err != nil {
		t.Fatal(err)
	}
	return v
}

func TestExtensionSetsParity(t *testing.T) {
	v := loadStatic(t)
	sets := v["ext_sets"].(map[string]any)
	got := map[string][]string{
		"archive": ArchiveExtensions,
		"audio":   AudioExtensions,
		"image":   ImageExtensions,
		"text":    TextExtensions,
		"video":   VideoExtensions,
	}
	for cat, wantAny := range sets {
		var want []string
		for _, e := range wantAny.([]any) {
			want = append(want, e.(string))
		}
		have := append([]string{}, got[cat]...)
		sort.Strings(have)
		if strings.Join(have, ",") != strings.Join(want, ",") {
			t.Errorf("%s sets differ", cat)
		}
	}
	for _, c := range v["file_types"].([]any) {
		m := c.(map[string]any)
		if got := FileType(m["ext"].(string)); got != m["expect"].(string) {
			t.Errorf("FileType(%q) = %q, want %q", m["ext"], got, m["expect"])
		}
	}
}

